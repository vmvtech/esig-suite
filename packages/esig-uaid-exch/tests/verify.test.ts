describe("verifyExchange", () => {
  it("verifies a genuine createExchange() output end to end, keys resolved from did:key verificationMethods", async () => {
    const agent = agentSigner("uuaid:foundation:agent:018f7abc");
    const issuer = issuerSigner("uuaid:foundation:certifier:018f7aaa");
    const exchange = await buildExchange(agent, issuer);

    const result = verifyExchange(exchange);
    expect(result.ok).toBe(true);
    expect(result.failures).toEqual([]);
    expect(result.agent.ok).toBe(true);
    expect(result.agent.keyFingerprint).toBe(fingerprint(agent.rawPublicKey));
    expect(result.issuer.ok).toBe(true);
    expect(result.issuer.keyFingerprint).toBe(fingerprint(issuer.rawPublicKey));
  });

  it("rejects an exchange whose body was tampered with after signing — both proofs fail", async () => {
    const agent = agentSigner("uuaid:foundation:agent:018f7abc");
    const issuer = issuerSigner("uuaid:foundation:certifier:018f7aaa");
    const exchange = await buildExchange(agent, issuer);

    const tampered: UaidExchange = {
      ...exchange,
      credentialSubject: {
        ...exchange.credentialSubject,
        exchange: { ...exchange.credentialSubject.exchange, purpose: "something else entirely" },
      },
    };

    const result = verifyExchange(tampered);
    expect(result.ok).toBe(false);
    expect(result.agent.ok).toBe(false);
    expect(result.issuer.ok).toBe(false);
    expect(result.failures).toHaveLength(2);
  });

  it("rejects when the wrong public key is supplied for a slot", async () => {
    const agent = agentSigner("uuaid:foundation:agent:018f7abc");
    const issuer = issuerSigner("uuaid:foundation:certifier:018f7aaa");
    const exchange = await buildExchange(agent, issuer);
    const wrongKey = agentSigner("someone-else").rawPublicKey;

    const result = verifyExchange(exchange, { agentPublicKey: wrongKey });
    expect(result.ok).toBe(false);
    expect(result.agent.ok).toBe(false);
    expect(result.issuer.ok).toBe(true); // issuer slot untouched
  });

  it("rejects when the two proofs are swapped (proofPurpose no longer matches its slot)", async () => {
    const agent = agentSigner("uuaid:foundation:agent:018f7abc");
    const issuer = issuerSigner("uuaid:foundation:certifier:018f7aaa");
    const exchange = await buildExchange(agent, issuer);
    const swapped: UaidExchange = { ...exchange, proof: [exchange.proof[1], exchange.proof[0]] };

    const result = verifyExchange(swapped);
    expect(result.ok).toBe(false);
    expect(result.agent.reason).toMatch(/proofPurpose mismatch/);
    expect(result.issuer.reason).toMatch(/proofPurpose mismatch/);
  });

  it("rejects a proof array that isn't exactly length 2", async () => {
    const agent = agentSigner("uuaid:foundation:agent:018f7abc");
    const issuer = issuerSigner("uuaid:foundation:certifier:018f7aaa");
    const exchange = await buildExchange(agent, issuer);
    const malformed: UaidExchange = { ...exchange, proof: [exchange.proof[0]] };

    const result = verifyExchange(malformed);
    expect(result.ok).toBe(false);
    expect(result.failures[0]).toMatch(/expected exactly 2 proofs/);
  });

  it("rejects an exchange whose issuer proof uses an unsupported cryptosuite", async () => {
    const agent = agentSigner("uuaid:foundation:agent:018f7abc");
    const issuer = issuerSigner("uuaid:foundation:certifier:018f7aaa");
    const exchange = await buildExchange(agent, issuer);
    const withBadCryptosuite: UaidExchange = {
      ...exchange,
      proof: [
        exchange.proof[0],
        { ...exchange.proof[1], cryptosuite: "eddsa-2022" as unknown as "eddsa-jcs-2022" },
      ],
    };

    const result = verifyExchange(withBadCryptosuite);
    expect(result.ok).toBe(false);
    expect(result.agent.ok).toBe(true);
    expect(result.issuer.reason).toMatch(/unsupported cryptosuite/);
  });
});
