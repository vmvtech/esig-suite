// ---------------------------------------------------------------------------
// Test helper: a real Ed25519 keypair wired up as an AgentSigner/IssuerSigner
// with a did:key verificationMethod (multicodec 0xed 0x01 + raw key,
// multibase 'z'). No existing test in this package builds real keys (both
// uaid-exch.test.ts's mockSigner() and revocation.test.ts use no crypto at
// all — grepped, confirmed) so this helper is new, per the ticket's
// instruction to reuse existing patterns where they exist and build one
// where they don't.
// ---------------------------------------------------------------------------

function makeEd25519KeyPair() {
  const { publicKey, privateKey } = generateKeyPairSync("ed25519");
  const spkiDer = publicKey.export({ type: "spki", format: "der" });
  const rawPublicKey = new Uint8Array(spkiDer.subarray(spkiDer.length - 32));
  const multicodec = new Uint8Array([0xed, 0x01, ...rawPublicKey]);
  const mb = encodeMultibase(multicodec, "z");
  const verificationMethod = `did:key:${mb}#${mb}`;
  return {
    rawPublicKey,
    verificationMethod,
    async sign(bytes: Uint8Array): Promise<string> {
      const sig = ed25519Sign(null, bytes, privateKey);
      return encodeMultibase(new Uint8Array(sig), "z");
    },
  };
}

function agentSigner(agentUuaid: string): AgentSigner & { rawPublicKey: Uint8Array } {
  const kp = makeEd25519KeyPair();
  return { agentUuaid, verificationMethod: kp.verificationMethod, sign: kp.sign, rawPublicKey: kp.rawPublicKey };
}

function issuerSigner(issuerDid: string): IssuerSigner & { rawPublicKey: Uint8Array } {
  const kp = makeEd25519KeyPair();
  return { issuerDid, verificationMethod: kp.verificationMethod, sign: kp.sign, rawPublicKey: kp.rawPublicKey };
}

function fingerprint(raw: Uint8Array): string {
  return createHash("sha256").update(raw).digest("hex");
}

async function buildExchange(agent: AgentSigner, issuer: IssuerSigner): Promise<UaidExchange> {
  return createExchange(
    {
      signingCredentialId: "uuaid:foundation:signing-credential:018f7ac8",
      principal: "did:web:acme.com",
      action: "sign.contract",
      counterparty: "did:web:customer.com",
      resource: { type: "application/pdf", sha256: "sha256:abc123", size: 184321 },
      purpose: "MSA Q3 renewal",
      soleControl: {
        challenge_type: "webauthn-prf",
        challenge_at: "2026-07-04T18:12:31.804Z",
        challenge_evidence_hash: "sha256:def456",
      },
      now: () => new Date("2026-07-04T18:12:33.412Z"),
      idFactory: () => "018f7ad5-4d3d-7ac8-8e11-4e6c9e2c6b3a",
    },
    agent,
    issuer
  );
}

