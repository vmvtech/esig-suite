describe("verifyDataIntegrityProof", () => {
  it("signs jcsBytes(document) directly (createExchange's construction) — a proof computed the W3C double-hash way over the same document+key is rejected", async () => {
    const kp = makeEd25519KeyPair();
    const document = { hello: "world", n: 1 };
    const proofShape = {
      type: "DataIntegrityProof" as const,
      cryptosuite: "eddsa-jcs-2022" as const,
      created: "2026-07-04T18:12:33.412Z",
      verificationMethod: kp.verificationMethod,
      proofPurpose: "authentication" as const,
    };

    // createExchange's actual construction (index.ts:229-234): sign
    // jcsBytes(document) directly — no proof-options hash at all.
    const realProof: DataIntegrityProof = {
      ...proofShape,
      proofValue: await kp.sign(jcsBytes(document)),
    };
    expect(verifyDataIntegrityProof(document, realProof).ok).toBe(true);

    // The W3C eddsa-jcs-2022 cryptosuite's construction instead:
    // sha256(JCS(proofConfig)) || sha256(JCS(document)), proofConfig being
    // the proof options (this same shape) without proofValue.
    const w3cBytes = new Uint8Array([
      ...createHash("sha256").update(jcsBytes(proofShape)).digest(),
      ...createHash("sha256").update(jcsBytes(document)).digest(),
    ]);
    const w3cProof: DataIntegrityProof = { ...proofShape, proofValue: await kp.sign(w3cBytes) };

    // This module mirrors createExchange's simpler construction, not the
    // W3C one — a proof computed the W3C way, over the identical document
    // and key, is rejected as a bad signature.
    const w3cResult = verifyDataIntegrityProof(document, w3cProof);
    expect(w3cResult.ok).toBe(false);
    expect(w3cResult.reason).toBe("signature verification failed");
  });

  it("rejects an unsupported proof type", async () => {
    const kp = makeEd25519KeyPair();
    const document = { a: 1 };
    const proof = {
      type: "Ed25519Signature2020",
      cryptosuite: "eddsa-jcs-2022",
      created: "2026-07-04T18:12:33.412Z",
      verificationMethod: kp.verificationMethod,
      proofPurpose: "authentication",
      proofValue: await kp.sign(jcsBytes(document)),
    } as unknown as DataIntegrityProof;
    const result = verifyDataIntegrityProof(document, proof);
    expect(result.ok).toBe(false);
    expect(result.reason).toMatch(/unsupported proof type/);
  });

  it("rejects an unsupported cryptosuite", async () => {
    const kp = makeEd25519KeyPair();
    const document = { a: 1 };
    const proof: DataIntegrityProof = {
      type: "DataIntegrityProof",
      cryptosuite: "eddsa-2022" as unknown as "eddsa-jcs-2022",
      created: "2026-07-04T18:12:33.412Z",
      verificationMethod: kp.verificationMethod,
      proofPurpose: "authentication",
      proofValue: await kp.sign(jcsBytes(document)),
    };
    const result = verifyDataIntegrityProof(document, proof);
    expect(result.ok).toBe(false);
    expect(result.reason).toMatch(/unsupported cryptosuite/);
  });

  it("rejects the wrong proofPurpose when one is expected", async () => {
    const kp = makeEd25519KeyPair();
    const document = { a: 1 };
    const proof: DataIntegrityProof = {
      type: "DataIntegrityProof",
      cryptosuite: "eddsa-jcs-2022",
      created: "2026-07-04T18:12:33.412Z",
      verificationMethod: kp.verificationMethod,
      proofPurpose: "authentication",
      proofValue: await kp.sign(jcsBytes(document)),
    };
    const result = verifyDataIntegrityProof(document, proof, {
      expectedProofPurpose: "assertionMethod",
    });
    expect(result.ok).toBe(false);
    expect(result.reason).toMatch(/proofPurpose mismatch/);
  });

  it("rejects a bad multibase proofValue", async () => {
    const kp = makeEd25519KeyPair();
    const document = { a: 1 };
    const proof: DataIntegrityProof = {
      type: "DataIntegrityProof",
      cryptosuite: "eddsa-jcs-2022",
      created: "2026-07-04T18:12:33.412Z",
      verificationMethod: kp.verificationMethod,
      proofPurpose: "authentication",
      proofValue: "not-a-multibase-value!",
    };
    const result = verifyDataIntegrityProof(document, proof);
    expect(result.ok).toBe(false);
    expect(result.reason).toMatch(/bad multibase proofValue/);
  });

  it("rejects an explicitly-passed public key of the wrong length", async () => {
    const kp = makeEd25519KeyPair();
    const document = { a: 1 };
    const proof: DataIntegrityProof = {
      type: "DataIntegrityProof",
      cryptosuite: "eddsa-jcs-2022",
      created: "2026-07-04T18:12:33.412Z",
      verificationMethod: kp.verificationMethod,
      proofPurpose: "authentication",
      proofValue: await kp.sign(jcsBytes(document)),
    };
    const result = verifyDataIntegrityProof(document, proof, { publicKey: new Uint8Array(16) });
    expect(result.ok).toBe(false);
    expect(result.reason).toMatch(/invalid public key length/);
  });

  it("rejects a tampered document (signature no longer matches)", async () => {
    const kp = makeEd25519KeyPair();
    const document = { a: 1 };
    const proof: DataIntegrityProof = {
      type: "DataIntegrityProof",
      cryptosuite: "eddsa-jcs-2022",
      created: "2026-07-04T18:12:33.412Z",
      verificationMethod: kp.verificationMethod,
      proofPurpose: "authentication",
      proofValue: await kp.sign(jcsBytes(document)),
    };
    const result = verifyDataIntegrityProof({ a: 2 }, proof);
    expect(result.ok).toBe(false);
    expect(result.reason).toBe("signature verification failed");
  });

  it("verifyChallengeProof round-trips a plain object with no embedded proof field", async () => {
    const kp = makeEd25519KeyPair();
    const challenge = {
      type: "esig-signer-challenge/v1",
      envelopeId: "018f7000",
      signerId: "signer-1",
      htmlSha256: "sha256:aaa",
      nonce: encodeMultibase(new Uint8Array(32).fill(7), "u"),
      issuedAt: "2026-08-27T00:00:00.000Z",
      expiresAt: "2026-08-27T00:15:00.000Z",
    };
    const proof: DataIntegrityProof = {
      type: "DataIntegrityProof",
      cryptosuite: "eddsa-jcs-2022",
      created: "2026-08-27T00:00:00.000Z",
      verificationMethod: kp.verificationMethod,
      proofPurpose: "authentication",
      proofValue: await kp.sign(jcsBytes(challenge)),
    };
    const ok = verifyChallengeProof(challenge, proof);
    expect(ok.ok).toBe(true);
    expect(ok.keyFingerprint).toBe(fingerprint(kp.rawPublicKey));

    const tampered = { ...challenge, nonce: encodeMultibase(new Uint8Array(32).fill(8), "u") };
    expect(verifyChallengeProof(tampered, proof).ok).toBe(false);
  });
});

