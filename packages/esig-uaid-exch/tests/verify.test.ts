describe("decodeMultibase / encodeMultibase", () => {
  it("round-trips base58btc ('z') including leading zero bytes", () => {
    const bytes = new Uint8Array([0, 0, 1, 2, 3, 255, 254]);
    const mb = encodeMultibase(bytes, "z");
    expect(mb[0]).toBe("z");
    expect(decodeMultibase(mb)).toEqual(bytes);
  });

  it("round-trips base64url ('u') without padding", () => {
    const bytes = new Uint8Array(32).fill(9);
    const mb = encodeMultibase(bytes, "u");
    expect(mb[0]).toBe("u");
    expect(mb).not.toContain("=");
    expect(decodeMultibase(mb)).toEqual(bytes);
  });

  it("rejects an unsupported multibase prefix", () => {
    expect(() => decodeMultibase("Zabc")).toThrow(/unsupported multibase prefix/);
  });

  it("rejects an empty string", () => {
    expect(() => decodeMultibase("")).toThrow();
  });

  it("rejects an invalid base58btc character (e.g. '0', excluded from the alphabet)", () => {
    expect(() => decodeMultibase("z0")).toThrow(/invalid base58btc character/);
  });
});

