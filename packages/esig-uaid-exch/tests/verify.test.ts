describe("publicKeyFromVerificationMethod", () => {
  it("decodes a did:key generated by this test's own signer (multicodec 0xed 0x01 + 32 bytes) back to the exact raw key", () => {
    const kp = makeEd25519KeyPair();
    expect(publicKeyFromVerificationMethod(kp.verificationMethod)).toEqual(kp.rawPublicKey);
  });

  it(
    "did:key W3C spec vector — decode/re-encode self-consistency only. " +
      "This test does NOT assert the raw key bytes for " +
      "did:key:z6MkhaXgBZDvotDkL5257faiztiGiC2QtKLGpbnnEGta2doK against an " +
      "independently-cited source: the ticket allowed falling back to a " +
      "self-generated round-trip when the raw bytes cannot be cited with " +
      "confidence, and that is the path taken here (see the previous test " +
      "for the full generate→encode→decode→match round trip). This test " +
      "only checks that decoding the published identifier succeeds, yields " +
      "the expected shape (34 bytes total: the 2-byte Ed25519 multicodec " +
      "prefix 0xed 0x01 + 32 key bytes), and that re-encoding those bytes " +
      "reproduces the original string.",
    () => {
      const did = "did:key:z6MkhaXgBZDvotDkL5257faiztiGiC2QtKLGpbnnEGta2doK";
      const mb = did.slice("did:key:".length);
      const decoded = decodeMultibase(mb);
      expect(decoded.length).toBe(34);
      expect(decoded[0]).toBe(0xed);
      expect(decoded[1]).toBe(0x01);
      expect(encodeMultibase(decoded, "z")).toBe(mb);
      // And the high-level accessor agrees this is a well-formed, usable key.
      expect(() => publicKeyFromVerificationMethod(did)).not.toThrow();
      expect(publicKeyFromVerificationMethod(did).length).toBe(32);
    }
  );

  it("accepts a raw Ed25519 JWK ({kty:'OKP', crv:'Ed25519', x})", () => {
    const kp = makeEd25519KeyPair();
    const x = encodeMultibase(kp.rawPublicKey, "u").slice(1); // strip the 'u' multibase prefix -> bare base64url
    const jwk = { kty: "OKP", crv: "Ed25519", x };
    expect(publicKeyFromVerificationMethod(jwk)).toEqual(kp.rawPublicKey);
  });

  it("rejects a JWK with the wrong crv", () => {
    const kp = makeEd25519KeyPair();
    const x = encodeMultibase(kp.rawPublicKey, "u").slice(1);
    expect(() =>
      publicKeyFromVerificationMethod({ kty: "OKP", crv: "P-256", x })
    ).toThrow(UnsupportedVerificationMethodError);
  });

  it("rejects a JWK whose x decodes to the wrong length", () => {
    expect(() =>
      publicKeyFromVerificationMethod({ kty: "OKP", crv: "Ed25519", x: "AQID" })
    ).toThrow(/expected 32-byte "x", got 3/);
  });

  it("rejects a did:key with the wrong multicodec prefix", () => {
    const wrongPrefix = new Uint8Array([0x00, 0x00, ...new Uint8Array(32)]);
    const did = `did:key:${encodeMultibase(wrongPrefix, "z")}`;
    expect(() => publicKeyFromVerificationMethod(did)).toThrow(
      UnsupportedVerificationMethodError
    );
    expect(() => publicKeyFromVerificationMethod(did)).toThrow(/multicodec prefix/);
  });

  it("rejects a JWK carrying extra key material (G6: e.g. a private 'd') even when kty/crv/x are otherwise valid", () => {
    const kp = makeEd25519KeyPair();
    const x = encodeMultibase(kp.rawPublicKey, "u").slice(1);
    expect(() =>
      publicKeyFromVerificationMethod({ kty: "OKP", crv: "Ed25519", x, d: "shouldNotBeHere" } as unknown as JsonWebKey)
    ).toThrow(UnsupportedVerificationMethodError);
    expect(() =>
      publicKeyFromVerificationMethod({ kty: "OKP", crv: "Ed25519", x, d: "shouldNotBeHere" } as unknown as JsonWebKey)
    ).toThrow(/extra field/);
    // An unrelated extra field is rejected the same way — the allowlist is
    // exact, not just "must not carry 'd'".
    expect(() =>
      publicKeyFromVerificationMethod({ kty: "OKP", crv: "Ed25519", x, kid: "key-1" } as unknown as JsonWebKey)
    ).toThrow(/extra field/);
  });

  it("rejects a verificationMethod that is neither did:key nor a recognized JWK — does not invent an 'ed25519:<hex>' form", () => {
    // Confirmed by grep across src/ and tests/: no "ed25519:" verification
    // method form exists anywhere in this package, so it is intentionally
    // unsupported here rather than invented.
    expect(() => publicKeyFromVerificationMethod("ed25519:" + "ab".repeat(32))).toThrow(
      UnsupportedVerificationMethodError
    );
    expect(() => publicKeyFromVerificationMethod("uuaid:foundation:agent:018f#sk-1")).toThrow(
      UnsupportedVerificationMethodError
    );
    expect(() => publicKeyFromVerificationMethod({} as never)).toThrow(
      UnsupportedVerificationMethodError
    );
  });
});

