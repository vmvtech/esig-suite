// Regenerates site/llms-full.txt — a plain-text digest of the public e-sig.org
// pages, for LLMs and agents that want the whole site instead of the brief in
// /llms.txt. Derived from the real HTML so the digest cannot drift from what
// humans see. Run: node scripts/ops/gen-llms-full.mjs

import { readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "../..");

export const PAGES = [
  ["Homepage", "https://e-sig.org/", "site/index.html"],
  ["Why e-sig", "https://e-sig.org/why-esig", "site/why-esig/index.html"],
  ["Public verifier", "https://e-sig.org/verify", "site/verify/index.html"],
  ["Pricing", "https://e-sig.org/pricing", "site/pricing/index.html"],
  ["vs DocuSign", "https://e-sig.org/vs/docusign", "site/vs/docusign/index.html"],
  ["vs Documenso", "https://e-sig.org/vs/documenso", "site/vs/documenso/index.html"],
  ["vs DocuSeal", "https://e-sig.org/vs/docuseal", "site/vs/docuseal/index.html"],
  ["For agents", "https://e-sig.org/agents", "site/agents/index.html"],
  ["Press kit", "https://e-sig.org/press", "site/press/index.html"],
  ["Legal notices", "https://e-sig.org/legal", "site/legal/index.html"],
  ["Terms of Use", "https://e-sig.org/terms", "site/terms/index.html"],
  ["Privacy Policy", "https://e-sig.org/privacy", "site/privacy/index.html"],
];

const ENTITIES = {
  amp: "&", lt: "<", gt: ">", quot: '"', apos: "'", "#39": "'",
  nbsp: " ", rarr: "→", larr: "←", mdash: "—", ndash: "–", hellip: "…",
  copy: "©", reg: "®", trade: "™", middot: "·", bull: "•", times: "×",
  ldquo: "\u201c", rdquo: "\u201d", lsquo: "\u2018", rsquo: "\u2019",
  laquo: "«", raquo: "»",
};

export function htmlToText(html) {
  let body = html
    .replace(/^[\s\S]*?<body[^>]*>/i, "")
    .replace(/<\/body>[\s\S]*$/i, "");
  body = body.replace(/<(script|style|noscript|svg|template)\b[\s\S]*?<\/\1>/gi, "");
  body = body.replace(/<(h[1-6])[^>]*>/gi, (_m, tag) => `\n${"#".repeat(Number(tag[1]))} `);
  body = body.replace(/<li[^>]*>/gi, "\n- ");
  body = body.replace(/<br\s*\/?>/gi, "\n");
  body = body.replace(/<\/(td|th)>/gi, " · ");
  body = body.replace(
    /<\/(p|div|section|article|header|footer|li|ul|ol|table|tr|blockquote|h[1-6]|pre|nav|main|figure|figcaption)>/gi,
    "\n",
  );
  body = body.replace(/<[^>]+>/g, "");
  body = body.replace(/&(#x?[0-9a-f]+|[a-z]+);/gi, (match, entity) => {
    if (entity[0] === "#") {
      const code =
        entity[1].toLowerCase() === "x"
          ? parseInt(entity.slice(2), 16)
          : parseInt(entity.slice(1), 10);
      return Number.isFinite(code) && code > 0
        ? String.fromCodePoint(code)
        : match;
    }
    return ENTITIES[entity] ?? match;
  });
  return body
    .split("\n")
    .map((line) => line.replace(/\s+/g, " ").trim())
    .join("\n")
    .replace(/\n{3,}/g, "\n\n")
    .trim();
}

export async function buildDigest() {
  const header = [
    "e-sig — full site digest for LLMs and agents",
    "Generated by scripts/ops/gen-llms-full.mjs from the live page HTML — do not edit by hand.",
    "Brief: https://e-sig.org/llms.txt · Source: https://github.com/vmvtech/esig-suite",
    "",
  ];
  const parts = [header.join("\n")];
  for (const [title, url, file] of PAGES) {
    const html = await readFile(join(ROOT, file), "utf8");
    const banner = `${"=".repeat(56)}\n${title} — ${url}\n${"=".repeat(56)}`;
    parts.push(`\n${banner}\n\n${htmlToText(html)}\n`);
  }
  return parts.join("\n");
}

const isMain = process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href;
if (isMain) {
  await writeFile(join(ROOT, "site/llms-full.txt"), `${await buildDigest()}\n`);
  console.log("✓ wrote site/llms-full.txt");
}
